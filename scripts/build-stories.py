"""Build the wildlife print story pages from the Word documents.

Source of truth is the folder of .docx files (default: D:\\GitHub\\Stories for the Print).
Each document is read top to bottom:

  * Title-style paragraph (or the first line)   -> the animal's name
  * "Park: ..." line                            -> the park
  * paragraphs after that                       -> the story text
  * any picture placed ABOVE the Photographer line -> the print photo(s)
  * "Photographer ..." line                     -> photographer name
  * any picture placed AT or BELOW that line    -> photographer portrait

The page heading is the "Top pick" for that animal in "Picture Title Ideas.txt"
in the same folder (falls back to the animal's name).

Output: wildlife/stories/<file-name-slug>.html plus wildlife/stories/images/.
The URL comes from the Word file's name, so editing the text, title or photos
never changes the link printed on the QR code. Renaming the .docx would.

Run by hand after editing the Word documents, then commit and push:
  python scripts/build-stories.py [source-folder]
"""

import hashlib
import html
import io
import os
import re
import sys
import zipfile

from PIL import Image, ImageOps

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else r"D:\GitHub\Stories for the Print"
OUT = os.path.join(REPO, "wildlife", "stories")
IMG_OUT = os.path.join(OUT, "images")
SITE = "https://4aholdingscompany.com"
MARK = "<!-- generated by scripts/build-stories.py from the Word document in Stories for the Print -->"

# Parks outside Sri Lanka (every other park gets ", Sri Lanka" after its name).
NON_SRI_LANKA_PARKS = {"great smoky mountains": "USA"}

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def load_titles():
    path = os.path.join(SRC, "Picture Title Ideas.txt")
    titles = {}
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return titles
    for m in re.finditer(r"^([A-Z][A-Z \-]+?) \((.+?)\)\s*\nTop pick:\s*(.+)$", text, re.M):
        titles[m.group(1).strip().lower()] = m.group(3).strip()
    return titles


def read_docx(path):
    """Return dict(name, park, paras, photographer, photos[bytes], portrait bytes|None)."""
    z = zipfile.ZipFile(path)
    doc = z.read("word/document.xml").decode("utf-8")
    rels_xml = z.read("word/_rels/document.xml.rels").decode("utf-8")
    rels = {}
    for m in re.finditer(r"<Relationship\b([^>]*)/?>", rels_xml):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
        if attrs.get("Type", "").endswith("/image"):
            rels[attrs["Id"]] = "word/" + attrs["Target"].lstrip("/").replace("word/", "", 1)

    body = re.search(r"<w:body>(.*)</w:body>", doc, re.S).group(1)
    paragraphs = []
    for p in re.findall(r"<w:p\b(?:(?!<w:p\b).)*?</w:p>|<w:p\b[^>]*/>", body, re.S):
        style = re.search(r'<w:pStyle w:val="([^"]+)"', p)
        # text runs, with tabs and line breaks kept as spaces
        parts = re.findall(r"<w:t(?:\s[^>]*)?>([^<]*)</w:t>|<w:(tab|br)\b[^>]*/>", p)
        text = "".join(t if t else " " for t, tag in parts)
        text = re.sub(r"\s+", " ", html.unescape(text)).strip()
        images = [rels[rid] for rid in re.findall(r'r:embed="([^"]+)"', p) if rid in rels]
        paragraphs.append({"style": style.group(1) if style else "", "text": text, "images": images})

    name = park = photographer = None
    paras, photos, portrait = [], [], None
    seen_photographer = False
    for p in paragraphs:
        t = p["text"]
        if name is None and t:
            name = t
        elif park is None and re.match(r"(?i)^park\s*:", t):
            park = re.sub(r"(?i)^park\s*:\s*", "", t)
        elif re.match(r"(?i)^photo(grapher|graphy|s)?\b", t) and not seen_photographer:
            seen_photographer = True
            photographer = re.sub(r"(?i)^photo(grapher|graphy|s)?(\s*by)?\s*[:\-]?\s*", "", t).strip() or None
        elif t and not seen_photographer:
            paras.append(t)
        for img in p["images"]:
            data = z.read(img)
            if seen_photographer:
                portrait = portrait or data
            else:
                photos.append(data)
    if not name or not paras:
        raise ValueError("no title or story text found")
    return dict(name=name, park=park or "", paras=paras, photographer=photographer,
                photos=photos, portrait=portrait)


def save_image(data, prefix, max_edge):
    """Resize to web size; file name carries a content hash so browsers never show a stale photo."""
    digest = hashlib.sha1(data).hexdigest()[:10]
    fname = f"{prefix}-{digest}.jpg"
    dest = os.path.join(IMG_OUT, fname)
    if not os.path.exists(dest):
        im = ImageOps.exif_transpose(Image.open(io.BytesIO(data))).convert("RGB")
        im.thumbnail((max_edge, max_edge), Image.LANCZOS)
        im.save(dest, "JPEG", quality=85, optimize=True, progressive=True)
    with Image.open(dest) as im:
        return fname, im.size


