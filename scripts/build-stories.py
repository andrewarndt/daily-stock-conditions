def build_page(slug, d, title):
    e = html.escape
    photos = ""
    for i, data in enumerate(d["photos"]):
        fname, (w, h) = save_image(data, f"{slug}-{i + 1}", 2000)
        loading = "eager" if i == 0 else "lazy"
        photos += (f'  <figure class="story-photo"><img src="images/{fname}" width="{w}" height="{h}" '
                   f'alt="{e(d["name"])}, photographed in {e(d["park"] or "Sri Lanka")}" loading="{loading}"></figure>\n')
    credit = ""
    if d["photographer"] or d["portrait"]:
        portrait = ""
        if d["portrait"]:
            fname, (w, h) = save_image(d["portrait"], "photographer", 400)
            portrait = f'<img src="images/{fname}" width="{w}" height="{h}" alt="{e(d["photographer"] or "The photographer")}">'
        credit = (f'  <aside class="story-credit">{portrait}<div>'
                  f'<p class="credit-label">Photographer</p>'
                  f'<p class="credit-name">{e(d["photographer"] or "")}</p>'
                  f'<a href="../index.html">See more of the collection &rarr;</a></div></aside>\n')
    park_line = d["park"]
    if d["park"] and "sri lanka" not in d["park"].lower():
        country = next((c for key, c in NON_SRI_LANKA_PARKS.items() if key in d["park"].lower()), "Sri Lanka")
        park_line = f'{d["park"]}, {country}'
    return PAGE.format(
        mark=MARK, title=e(title), name=e(d["name"]), park_line=e(park_line),
        description=e(f'The story behind {title}, a wildlife print of {d["name"]}'
                      + (f' from {d["park"]}' if d["park"] else "") + "."),
        url=f"{SITE}/wildlife/stories/{slug}.html",
        photos=photos, credit=credit,
        paras="\n".join(f"    <p>{e(p)}</p>" for p in d["paras"]),
    )


def main():
    os.makedirs(IMG_OUT, exist_ok=True)
    titles = load_titles()
    built, failed = set(), set()
    for fn in sorted(os.listdir(SRC)):
        if not fn.lower().endswith(".docx") or fn.startswith("~$"):
            continue  # ~$ files are Word's lock files while a document is open
        slug = slugify(fn[:-5])
        try:
            d = read_docx(os.path.join(SRC, fn))
        except Exception as ex:  # half-saved or unexpected doc: keep the last good page
            print(f"SKIP {fn}: {ex}")
            failed.add(slug)
            continue
        title = titles.get(d["name"].lower(), d["name"])
        page = build_page(slug, d, title)
        dest = os.path.join(OUT, f"{slug}.html")
        old = open(dest, encoding="utf-8").read() if os.path.exists(dest) else None
        if old is None or old.replace("\r\n", "\n") != page:
            with open(dest, "w", encoding="utf-8", newline="\n") as f:
                f.write(page)
            print(f"UPDATED {slug}.html  ({title}; {len(d['paras'])} paragraphs, {len(d['photos'])} photo(s))")
        built.add(slug)

    # Remove pages (and images) whose Word document is gone, never ones that only failed to read.
    keep_imgs = set()
    for fn in os.listdir(OUT):
        path = os.path.join(OUT, fn)
        if not fn.endswith(".html"):
            continue
        text = open(path, encoding="utf-8").read()
        if MARK not in text:
            continue
        slug = fn[:-5]
        if slug not in built and slug not in failed:
            os.remove(path)
            print(f"REMOVED {fn} (its Word document is gone)")
            continue
        keep_imgs.update(re.findall(r'src="images/([^"]+)"', text))
    for fn in os.listdir(IMG_OUT):
        if fn not in keep_imgs:
            os.remove(os.path.join(IMG_OUT, fn))


if __name__ == "__main__":
    main()
